const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const context=vm.createContext({window:{}});
for(const file of ['engine_foundation_v1.js','character_environment_v1.js','weather_system_v1.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../assets',file),'utf8'),context);
const {DungeonEngineV1:e,DungeonGameTimeV1:t,DungeonWeatherV1:w}=context.window;
let events=[],order=[];
e.register({id:'weather',version:'1',requires:['engine.time']});
e.register({id:'care',version:'1',requires:['weather']});
e.onTime('care',(actor,event)=>{events.push(event);order.push('care');});
e.onTime('weather',(actor,event)=>{w.exposure(actor,event.fromScene==='inn');order.push('weather');});
const actor={worldMinutes:1435,scene:'wreck',seed:2,equipmentV1:{outer:'starter_cloak'},hp:16};
w.exposure(actor,false);
t.advance(actor,10,{reason:'travel:walk',toScene:'inn'});
assert.equal(actor.worldMinutes,1445);assert.equal(events[0].daysCrossed,1);assert.equal(events[0].fromScene,'wreck');assert.equal(events[0].toScene,'inn');
assert.equal(order.join(','),'weather,care');assert.equal(actor.weatherExposure.minute,1445);
actor.scene='inn';w.exposure(actor,true);
const old=JSON.stringify(actor.weatherExposure);t.advance(actor,0);assert.equal(events.length,1);assert.equal(JSON.stringify(actor.weatherExposure),old);
t.advance(actor,20,{reason:'rest'});assert.equal(actor.worldMinutes,1465);
t.nextMorning(actor);assert.equal(actor.worldMinutes,3360);assert.equal(actor.hp,16);
assert.equal(t.format(960),'第1日 16:00');assert.equal(t.parts(300).period,'dawn');assert.equal(t.parts(480).period,'day');assert.equal(t.parts(1020).period,'dusk');assert.equal(t.parts(1200).period,'night');
assert.equal(t.normalize({flags:{morning:true}}),1920);
assert.throws(()=>t.advance(actor,-1));assert.throws(()=>t.advance(actor,1.5));assert.throws(()=>e.register({id:'weather',version:'2'}));
e.register({id:'blocked',version:'1',requires:['missing']});e.onTime('blocked',()=>{throw Error('must not run');});
e.register({id:'broken',version:'1'});e.onTime('broken',()=>{throw Error('test fault');});
t.advance(actor,1);assert.equal(e.status().find(m=>m.id==='blocked').state,'blocked');assert(e.diagnostics().faults.some(f=>f.id==='broken'));assert(e.diagnostics().faults.some(f=>f.id==='blocked'));
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');assert(!/s\.worldMinutes\s*(\+=|-=|=(?!=)|\+\+|--)/.test(html));assert(html.includes('engineDiagnosticsBtn'));
console.log('Shared engine clock and registry regression tests passed.');
