const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const window={};vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../assets/lantern_resource_core_v1.js'),'utf8'),{window});
const core=window.LanternResourceCoreV1,parts={},daily={collected:0};
assert.equal(core.collect(parts,daily,'木材'),true);
assert.equal(core.collect(parts,daily,'蘑菇',{commit:()=>false}),false);
assert.equal(daily.collected,1);
assert.equal(core.collect(parts,daily,'蘑菇'),true);
assert.equal(core.collect(parts,daily,'木材'),false);
assert.equal(parts.木材,1);
assert.equal(core.apply(parts,{'木材':2,'布料':3}),true);
assert.equal(core.apply(parts,{'木材':-1,'布料':-4}),false);
assert.equal(parts.木材,3);
assert.equal(parts.布料,3);
assert.equal(core.consume(parts,'木材',2),true);
assert.equal(parts.木材,1);
assert.equal(core.consume(parts,'木材',2),false);
assert.equal(core.add(parts,'__proto__',1),false);
assert.equal(core.add(parts,'木材',-1),false);
assert.equal(core.apply(parts,{'木材':1},{commit:()=>false}),false);
assert.equal(parts.木材,1);
assert.deepEqual(JSON.parse(JSON.stringify(parts)),parts);
console.log('Lantern resource core passed');
